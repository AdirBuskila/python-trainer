"""Bundle data/ch*.py into course.js (window.COURSE) for the web app.

Usage: python tools/build.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from validate import chapter_files, load  # noqa: E402


def main():
    chapters = []
    for path in chapter_files():
        ch = load(path)
        for ex in ch["exercises"]:
            ex.setdefault("exam", False)
        chapters.append(ch)
    out = ROOT / "course.js"
    payload = json.dumps({"chapters": chapters}, ensure_ascii=False, indent=1)
    out.write_text("// Generated by tools/build.py - do not edit by hand.\nwindow.COURSE = " + payload + ";\n", encoding="utf-8")
    n = sum(len(c["exercises"]) for c in chapters)
    print(f"Wrote {out.name}: {len(chapters)} chapters, {n} exercises")


if __name__ == "__main__":
    main()
